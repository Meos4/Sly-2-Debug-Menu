#include "Camera.h"

#include "Menu.h"
#include "Profile.h"

void Camera_setMrd(u32 mode)
{
	WORD(MRD_POSITION) = WORD(NATIVE_CAMERA + PROFILE_CAMERA_POSITION);
	WORD(MRD_POSITION + 4) = WORD(NATIVE_CAMERA + PROFILE_CAMERA_POSITION + 4);
	WORD(MRD_POSITION + 8) = WORD(NATIVE_CAMERA + PROFILE_CAMERA_POSITION + 8);
	WORD(MRD_POSITION + 12) = WORD(NATIVE_CAMERA + PROFILE_CAMERA_POSITION + 12);
	WORD(MRD_MASK) = WORD(NATIVE_CAMERA + PROFILE_CAMERA_REGION_MASK);
	WORD(MRD_MODE) = mode;
}
